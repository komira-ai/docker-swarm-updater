//! Tests of `release version`, `stamp`, `check-static` and `sums`.

use std::os::unix::fs::PermissionsExt as _;

use super::*;

fn s(v: &[&str]) -> Vec<String> {
    v.iter().map(|x| (*x).to_owned()).collect()
}

const MANIFEST: &str = "[workspace]\nmembers = [\"crates/*\"]\n\n[workspace.package]\nedition = \"2024\"\nversion = \"0.1.0\"\n\n[workspace.dependencies]\nfoo = { version = \"0.1.0\" }\n\n[package]\nversion = \"0.1.0\"\n";

const LOCK: &str = "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"a\"\nversion = \"0.1.0\"\ndependencies = [\n \"foo\",\n]\n\n[[package]]\nname = \"foo\"\nversion = \"0.1.0\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\nchecksum = \"00\"\n\n[[package]]\nname = \"other\"\nversion = \"0.2.0\"\n\n[[package]]\nname = \"z\"\nversion = \"0.1.0\"\n";

fn workspace(manifest: &str, lock: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("Cargo.toml"), manifest).unwrap();
    std::fs::write(dir.path().join("Cargo.lock"), lock).unwrap();
    dir
}

fn root_args(verb: &[&str], dir: &Path) -> Vec<String> {
    let mut args = s(verb);
    args.push("--root".into());
    args.push(dir.to_string_lossy().into_owned());
    args
}

#[test]
fn version_is_the_workspace_major_and_minor_and_the_commit_count() {
    let dir = workspace(MANIFEST, LOCK);
    let report = run(&root_args(&["version", "--commit-count", "42"], dir.path())).unwrap();
    assert!(report.passed);
    assert_eq!(report.text, "version=0.1.42\n");
    assert_eq!(
        run(&root_args(&["version", "--commit-count", "x"], dir.path())).unwrap_err(),
        "--commit-count \"x\" is not a number"
    );
    assert_eq!(
        run(&s(&["version"])).unwrap_err(),
        "--commit-count is required"
    );
    let bad = workspace(
        &MANIFEST.replace("\"0.1.0\"\n\n[workspace.dep", "\"0.1\"\n\n[workspace.dep"),
        LOCK,
    );
    assert_eq!(
        run(&root_args(&["version", "--commit-count", "1"], bad.path())).unwrap_err(),
        "version \"0.1\" is not X.Y.Z"
    );
    let unparsable = workspace("[workspace", LOCK);
    assert!(
        run(&root_args(
            &["version", "--commit-count", "1"],
            unparsable.path()
        ))
        .unwrap_err()
        .starts_with("Cargo.toml: ")
    );
    let missing = tempfile::tempdir().unwrap();
    assert!(
        run(&root_args(
            &["version", "--commit-count", "1"],
            missing.path()
        ))
        .unwrap_err()
        .starts_with("reading ")
    );
}

#[test]
fn stamp_sets_the_workspace_version_and_only_the_workspace_crates_in_the_lock() {
    let dir = workspace(MANIFEST, LOCK);
    let report = run(&root_args(&["stamp", "--version", "0.1.42"], dir.path())).unwrap();
    assert_eq!(report.text, "stamp: 0.1.42\n");
    assert_eq!(
        std::fs::read_to_string(dir.path().join("Cargo.toml")).unwrap(),
        MANIFEST.replacen(
            "edition = \"2024\"\nversion = \"0.1.0\"",
            "edition = \"2024\"\nversion = \"0.1.42\"",
            1
        )
    );
    // The two workspace crates at 0.1.0 move; the registry crate at 0.1.0 and the crate at
    // another version do not.
    assert_eq!(
        std::fs::read_to_string(dir.path().join("Cargo.lock")).unwrap(),
        LOCK.replacen(
            "name = \"a\"\nversion = \"0.1.0\"",
            "name = \"a\"\nversion = \"0.1.42\"",
            1
        )
        .replacen(
            "name = \"z\"\nversion = \"0.1.0\"",
            "name = \"z\"\nversion = \"0.1.42\"",
            1
        )
    );
}

#[test]
fn stamp_refuses_a_bad_version_or_a_workspace_it_cannot_stamp() {
    let dir = workspace(MANIFEST, LOCK);
    for bad in ["1.2", "1.2.x", "1..2", "v1.2.3"] {
        assert_eq!(
            run(&root_args(&["stamp", "--version", bad], dir.path())).unwrap_err(),
            format!("version {bad:?} is not X.Y.Z")
        );
    }
    // A [workspace.package] whose version is not on a line of its own.
    let inline = workspace(
        "[workspace.package]\nversion=\"0.1.0\"\n[workspace]\n",
        LOCK,
    );
    assert_eq!(
        run(&root_args(&["stamp", "--version", "0.1.1"], inline.path())).unwrap_err(),
        "Cargo.toml: no `version = \"0.1.0\"` line in [workspace.package]"
    );
    // A lock with no workspace crate at that version.
    let lock = workspace(
        MANIFEST,
        "version = 4\n\n[[package]]\nname = \"a\"\nversion = \"9.9.9\"\n",
    );
    assert_eq!(
        run(&root_args(&["stamp", "--version", "0.1.1"], lock.path())).unwrap_err(),
        "Cargo.lock: no workspace package at 0.1.0"
    );
    let no_packages = workspace(MANIFEST, "version = 4\n");
    assert_eq!(
        run(&root_args(
            &["stamp", "--version", "0.1.1"],
            no_packages.path()
        ))
        .unwrap_err(),
        "Cargo.lock: no workspace package at 0.1.0"
    );
    let no_lock = tempfile::tempdir().unwrap();
    std::fs::write(no_lock.path().join("Cargo.toml"), MANIFEST).unwrap();
    assert!(
        run(&root_args(&["stamp", "--version", "0.1.1"], no_lock.path()))
            .unwrap_err()
            .starts_with("reading ")
    );
    // Nothing is written when either file is refused.
    assert_eq!(
        std::fs::read_to_string(lock.path().join("Cargo.toml")).unwrap(),
        MANIFEST
    );
}

#[test]
fn stamp_reports_a_file_it_cannot_write() {
    for name in ["Cargo.toml", "Cargo.lock"] {
        let dir = workspace(MANIFEST, LOCK);
        let path = dir.path().join(name);
        std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o444)).unwrap();
        let error = run(&root_args(&["stamp", "--version", "0.1.1"], dir.path())).unwrap_err();
        assert!(
            error.starts_with(&format!("writing {}", path.display())),
            "{error}"
        );
    }
}

/// An ELF64 little-endian header with `types` as its program headers' types.
fn elf(types: &[u32]) -> Vec<u8> {
    let mut bytes = vec![0u8; 64];
    bytes[..4].copy_from_slice(b"\x7fELF");
    bytes[4] = 2;
    bytes[5] = 1;
    bytes[0x20..0x28].copy_from_slice(&64u64.to_le_bytes());
    bytes[0x36..0x38].copy_from_slice(&56u16.to_le_bytes());
    bytes[0x38..0x3a].copy_from_slice(&u16::try_from(types.len()).unwrap().to_le_bytes());
    for t in types {
        let mut ph = vec![0u8; 56];
        ph[..4].copy_from_slice(&t.to_le_bytes());
        bytes.extend(ph);
    }
    bytes
}

#[test]
fn a_binary_with_a_program_interpreter_is_not_static() {
    // PT_LOAD, PT_DYNAMIC: a static-pie binary.
    assert_eq!(needs_interpreter(&elf(&[1, 2])), Ok(false));
    assert_eq!(needs_interpreter(&elf(&[])), Ok(false));
    // PT_PHDR, PT_INTERP, PT_LOAD.
    assert_eq!(needs_interpreter(&elf(&[6, 3, 1])), Ok(true));
}

#[test]
fn a_file_that_is_not_a_whole_elf64_is_refused() {
    assert_eq!(
        needs_interpreter(b"#!/bin/sh\n"),
        Err("not an ELF file".into())
    );
    let mut elf32 = elf(&[]);
    elf32[4] = 1;
    assert_eq!(
        needs_interpreter(&elf32),
        Err("not a little-endian 64-bit ELF file".into())
    );
    let truncated = Err("the ELF header or a program header is truncated".to_owned());
    let whole = elf(&[1]);
    assert_eq!(needs_interpreter(&whole[..0x28 - 1]), truncated);
    assert_eq!(needs_interpreter(&whole[..0x3a - 1]), truncated);
    assert_eq!(needs_interpreter(&whole[..whole.len() - 53]), truncated);
    // A program header offset past the end, and one past the address space.
    let mut far = elf(&[1]);
    far[0x20..0x28].copy_from_slice(&u64::MAX.to_le_bytes());
    assert_eq!(needs_interpreter(&far), truncated);
}

#[test]
fn check_static_passes_a_static_binary_and_fails_this_dynamic_test_binary() {
    let dir = tempfile::tempdir().unwrap();
    let path = dir.path().join("bin");
    std::fs::write(&path, elf(&[1])).unwrap();
    let report = run(&s(&["check-static", "--binary", &path.to_string_lossy()])).unwrap();
    assert!(report.passed);
    assert_eq!(
        report.text,
        format!("check-static: {} is static\n", path.display())
    );

    // The test binary itself is linked against the host's libc, so it has an interpreter.
    let me = std::env::current_exe().unwrap();
    let report = run(&s(&["check-static", "--binary", &me.to_string_lossy()])).unwrap();
    assert!(!report.passed);
    assert_eq!(
        report.text,
        format!(
            "check-static: {} needs a program interpreter\n",
            me.display()
        )
    );

    assert!(
        run(&s(&["check-static", "--binary", "/nonexistent/bin"]))
            .unwrap_err()
            .starts_with("reading /nonexistent/bin")
    );
}

fn release_dir(version: &str) -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    for name in assets(version) {
        std::fs::write(dir.path().join(&name), name.as_bytes()).unwrap();
    }
    dir
}

#[test]
fn the_assets_are_a_binary_and_an_image_per_platform() {
    assert_eq!(
        assets("1.2.3"),
        [
            "docker-swarm-updater-1.2.3-linux-arm64",
            "docker-swarm-updater-1.2.3-linux-arm64.image.tar",
            "docker-swarm-updater-1.2.3-linux-x86_64",
            "docker-swarm-updater-1.2.3-linux-x86_64.image.tar",
        ]
    );
}

#[test]
fn sums_writes_sha256sums_over_exactly_the_releases_files() {
    let dir = release_dir("1.2.3");
    let args = s(&[
        "sums",
        "--dir",
        &dir.path().to_string_lossy(),
        "--version",
        "1.2.3",
    ]);
    let report = run(&args).unwrap();
    assert!(report.passed);
    let expected: String = assets("1.2.3")
        .iter()
        .map(|n| format!("{}  {n}\n", hex::encode(Sha256::digest(n.as_bytes()))))
        .collect();
    let written = std::fs::read_to_string(dir.path().join("SHA256SUMS")).unwrap();
    assert_eq!(written, expected);
    assert_eq!(
        report.text,
        format!(
            "sha256={}\n",
            hex::encode(Sha256::digest(expected.as_bytes()))
        )
    );
}

#[test]
fn sums_fails_on_a_missing_or_an_extra_file() {
    let missing = release_dir("1.2.3");
    std::fs::remove_file(
        missing
            .path()
            .join("docker-swarm-updater-1.2.3-linux-arm64"),
    )
    .unwrap();
    let extra = release_dir("1.2.3");
    std::fs::write(extra.path().join("notes.txt"), "x").unwrap();
    // A directory left from an earlier run: SHA256SUMS is never summed.
    let rerun = release_dir("1.2.3");
    std::fs::write(rerun.path().join("SHA256SUMS"), "x").unwrap();
    // The wrong version.
    let other = release_dir("1.2.4");
    for dir in [&missing, &extra, &rerun, &other] {
        let report = run(&s(&[
            "sums",
            "--dir",
            &dir.path().to_string_lossy(),
            "--version",
            "1.2.3",
        ]))
        .unwrap();
        assert!(!report.passed);
        assert!(report.text.starts_with("sums: "), "{}", report.text);
        assert!(
            report
                .text
                .ends_with(&format!("the release is {:?}\n", assets("1.2.3")))
        );
    }
    assert!(!missing.path().join("SHA256SUMS").exists());
}

#[test]
fn sums_reports_what_it_cannot_read_or_write() {
    assert!(
        run(&s(&["sums", "--dir", "/nonexistent", "--version", "1"]))
            .unwrap_err()
            .starts_with("reading /nonexistent")
    );
    // An asset name that is a directory cannot be read.
    let dir = release_dir("1.2.3");
    let name = dir.path().join("docker-swarm-updater-1.2.3-linux-arm64");
    std::fs::remove_file(&name).unwrap();
    std::fs::create_dir(&name).unwrap();
    let args = s(&[
        "sums",
        "--dir",
        &dir.path().to_string_lossy(),
        "--version",
        "1.2.3",
    ]);
    assert!(
        run(&args)
            .unwrap_err()
            .starts_with(&format!("reading {}", name.display()))
    );
    // A directory SHA256SUMS cannot be written into.
    let dir = release_dir("1.2.3");
    std::fs::set_permissions(dir.path(), std::fs::Permissions::from_mode(0o555)).unwrap();
    let args = s(&[
        "sums",
        "--dir",
        &dir.path().to_string_lossy(),
        "--version",
        "1.2.3",
    ]);
    let error = run(&args).unwrap_err();
    std::fs::set_permissions(dir.path(), std::fs::Permissions::from_mode(0o755)).unwrap();
    assert!(error.starts_with("writing "), "{error}");
}

#[test]
fn a_bad_command_line_is_refused() {
    assert!(
        run(&s(&[]))
            .unwrap_err()
            .starts_with("usage: xtask release")
    );
    assert!(
        run(&s(&["publish"]))
            .unwrap_err()
            .starts_with("usage: xtask release")
    );
    assert!(
        run(&s(&["sums", "--bogus", "x"]))
            .unwrap_err()
            .starts_with("unknown flag --bogus; usage: xtask release")
    );
    assert_eq!(
        run(&s(&["sums", "--dir"])).unwrap_err(),
        "--dir needs a value"
    );
    assert_eq!(
        run(&s(&["sums", "--dir", "a", "--dir", "b"])).unwrap_err(),
        "--dir is given twice"
    );
    assert_eq!(run(&s(&["stamp"])).unwrap_err(), "--version is required");
}
